from __future__ import annotations

import argparse
import os
import re
import shutil
from pathlib import Path

WC_LIST = [
    "ctGIm", "ctGRe",
    "cQj38", "cQj18",
    "cQu8", "cQd8", "ctj8", "ctu8", "ctd8",
    "cQj31", "cQj11",
    "cQu1", "cQd1", "ctj1", "ctu1", "ctd1",
]

POINTS = [-4, -2, 0, 2, 4]


def point_tag(x: int) -> str:
    if x < 0:
        return f"m{abs(x)}"
    if x > 0:
        return f"p{x}"
    return "p0"


def read_required(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(f"Missing required file: {path}")
    return path.read_text()




def sanitize_run_card(run_text: str) -> str:
    """Keep the original run_card content, but remove options incompatible with MG5 2.6.5.

    MG5_aMC 2.6.5 does not define SDE_STRATEGY in its generated Fortran include.
    If the run card contains sde_strategy, setrun.f compilation fails with:
      Error: Symbol 'sde_strategy' has no IMPLICIT type
    """
    cleaned_lines = []
    for line in run_text.splitlines():
        if re.search(r"\bsde_strategy\b", line, flags=re.I):
            continue
        cleaned_lines.append(line)
    return "\n".join(cleaned_lines) + "\n"


def replace_output_name(proc_text: str, new_name: str) -> str:
    """Replace only the MG output line, preserving flags such as -nojpeg."""
    return re.sub(r"(?m)^\s*output\s+\S+(.*)$", rf"output {new_name}\1", proc_text)


def rewrite_customize(base_text: str, active_wc: str, active_value: int) -> str:
    """Set all known WCs to 0, then set the active WC to active_value.

    Preserve all non-WC settings from the base customize card, such as LambdaSMEFT,
    masses, and Yukawas.
    """
    wc_seen = set()
    out_lines = []

    number = r"[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?|[-+]?\.\d+(?:[eE][-+]?\d+)?"
    wc_line_re = re.compile(rf"^(\s*set\s+param_card\s+)(\S+)(\s+)({number})(.*)$")

    for line in base_text.splitlines():
        m = wc_line_re.match(line)
        if m and m.group(2) in WC_LIST:
            wc = m.group(2)
            val = float(active_value if wc == active_wc else 0.0)
            out_lines.append(f"{m.group(1)}{wc}{m.group(3)}{val:.8e}{m.group(5)}")
            wc_seen.add(wc)
        else:
            out_lines.append(line)

    # If a WC was missing from the base customize card, add it explicitly.
    for wc in WC_LIST:
        if wc not in wc_seen:
            val = float(active_value if wc == active_wc else 0.0)
            out_lines.append(f"set param_card {wc} {val:.8e}")

    out_lines.append("")
    return "\n".join(out_lines)


def copy_optional_cards(base_dir: Path, base_name: str, card_dir: Path, name: str) -> None:
    """Copy optional companion cards/scripts except reweight cards."""
    optional_suffixes = [
        "extramodels",
        "madspin_card",
        "param_card",
        "cuts",
        "FKS_params",
        "setscales",
        "patch_me.sh",
        "externaltarball",
    ]

    for suffix in optional_suffixes:
        # Normal card convention: <base>_<suffix>.dat
        src_dat = base_dir / f"{base_name}_{suffix}.dat"
        if src_dat.exists():
            shutil.copy2(src_dat, card_dir / f"{name}_{suffix}.dat")

        # Shell script convention, for patch_me.sh etc.
        src_raw = base_dir / f"{base_name}_{suffix}"
        if src_raw.exists() and src_raw.is_file():
            shutil.copy2(src_raw, card_dir / f"{name}_{suffix}")


def remove_generated_dirs(out_parent: Path, base_name: str) -> None:
    """Remove only directories generated by this script; never delete the whole cards area."""
    if not out_parent.exists():
        return

    pattern = re.compile(rf"^{re.escape(base_name)}_({'|'.join(map(re.escape, WC_LIST))})_(m4|m2|p0|p2|p4)$")
    for child in out_parent.iterdir():
        if child.is_dir() and pattern.match(child.name):
            shutil.rmtree(child)

    for extra in [out_parent / "gridpack_card_manifest.txt"]:
        if extra.exists():
            extra.unlink()


def write_run_script(
    run_script: Path,
    manifest: list[tuple[str, Path]],
    carddir_for_gridpack: str,
    queue: str,
    jobstep: str,
    scram_arch: str,
    cmssw_version: str,
) -> None:
    """Write one standalone gridpack_generation.sh command per generated card dir.

    This intentionally avoids a bash loop so a SLURM maker can read/split
    the file line-by-line and create one job per gridpack command.
    """
    lines = [
        "#!/usr/bin/env bash",
        "",
        "# Auto-generated by make_no_reweight_gridpack_cards.py",
        "# One standalone gridpack_generation.sh command per gridpack job.",
        "# Environment setup belongs in each SLURM job, not here.",
        "# To submit with Make_SlurmJobs_gridpacks.py, split/read the non-comment command lines.",
        "",
    ]

    for name, _ in manifest:
        carddir_this = f"{carddir_for_gridpack}/{name}"
        cmd = [
            "./gridpack_generation.sh",
            shlex_quote(name),
            shlex_quote(carddir_this),
            shlex_quote(queue),
            shlex_quote(jobstep),
            shlex_quote(scram_arch),
            shlex_quote(cmssw_version),
        ]
        lines.append(" ".join(cmd))

    lines.append("")
    run_script.write_text("\n".join(lines))
    run_script.chmod(run_script.stat().st_mode | 0o111)


def shlex_quote(x: str) -> str:
    """Small local quote helper to avoid importing shlex at old sites."""
    s = str(x)
    if re.match(r"^[A-Za-z0-9_./:=+-]+$", s):
        return s
    return "'" + s.replace("'", "'\"'\"'") + "'"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--base-dir",
        default="addons/cards/SMEFTsim_topU3l_MwScheme_UFO_ctGpatched/TT01j2lBSMRef",
        help="Base card directory to clone from.",
    )
    parser.add_argument("--base-name", default="TT01j2lBSMRef")
    parser.add_argument(
        "--out-parent",
        default="addons/cards/SMEFTsim_topU3l_MwScheme_UFO_ctGpatched",
        help="Parent directory for generated card directories. Default puts them parallel to TT01j2lBSMRef.",
    )
    parser.add_argument("--run-script", default="run_all_80_no_reweight_gridpacks.sh")
    parser.add_argument("--queue", default="local")
    parser.add_argument("--jobstep", default="ALL")
    parser.add_argument("--scram-arch", default="slc7_amd64_gcc700")
    parser.add_argument("--cmssw-version", default="CMSSW_10_6_19")
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove only previously generated TT01j2lBSMRef_<WC>_<point> directories under --out-parent before writing.",
    )
    args = parser.parse_args()

    base_dir = Path(args.base_dir).resolve()
    out_parent = Path(args.out_parent).resolve()
    base_name = args.base_name

    proc_text = read_required(base_dir / f"{base_name}_proc_card.dat")
    run_text = sanitize_run_card(read_required(base_dir / f"{base_name}_run_card.dat"))
    customize_text = read_required(base_dir / f"{base_name}_customizecards.dat")

    if args.clean:
        remove_generated_dirs(out_parent, base_name)
    out_parent.mkdir(parents=True, exist_ok=True)

    manifest: list[tuple[str, Path]] = []
    cwd = Path.cwd().resolve()

    for wc in WC_LIST:
        for point in POINTS:
            name = f"{base_name}_{wc}_{point_tag(point)}"
            card_dir = out_parent / name
            if card_dir.exists():
                shutil.rmtree(card_dir)
            card_dir.mkdir(parents=True, exist_ok=True)

            (card_dir / f"{name}_proc_card.dat").write_text(replace_output_name(proc_text, name))
            (card_dir / f"{name}_run_card.dat").write_text(run_text)
            (card_dir / f"{name}_customizecards.dat").write_text(rewrite_customize(customize_text, wc, point))
            copy_optional_cards(base_dir, base_name, card_dir, name)

            # Safety: make sure no reweight card survived by accident.
            for rw in card_dir.glob("*reweight_card.dat"):
                rw.unlink()

            manifest.append((name, card_dir.relative_to(cwd)))

    manifest_path = out_parent / "gridpack_card_manifest.txt"
    with manifest_path.open("w") as f:
        for name, rel_dir in manifest:
            f.write(f"{name} {rel_dir}\n")

    # Pass the parent directory that directly contains the generated card directories.
    try:
        carddir_for_gridpack = out_parent.relative_to(cwd).as_posix()
    except ValueError:
        carddir_for_gridpack = out_parent.as_posix()

    run_script = Path(args.run_script).resolve()
    write_run_script(
        run_script=run_script,
        manifest=manifest,
        carddir_for_gridpack=carddir_for_gridpack,
        queue=args.queue,
        jobstep=args.jobstep,
        scram_arch=args.scram_arch,
        cmssw_version=args.cmssw_version,
    )

    print(f"[OK] Wrote {len(manifest)} no-reweight card directories under: {out_parent}")
    print(f"[OK] Manifest: {manifest_path}")
    print(f"[OK] Runner: {run_script}")
    print("[OK] No *_reweight_card.dat files were created.")
    print("[OK] Generated card dirs are directly inside SMEFTsim_topU3l_MwScheme_UFO_ctGpatched, parallel to TT01j2lBSMRef.")


if __name__ == "__main__":
    main()
