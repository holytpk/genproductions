#!/usr/bin/env python3
"""
Generate 80 SMEFTsim gridpack card directories from a base card directory,
one single-Wilson-coefficient point per directory, with NO reweight card copied.

Run from genproductions/bin/MadGraph5_aMCatNLO:

  python3 make_80_no_reweight_gridpack_cards.py --clean

Default layout:

  addons/cards/SMEFTsim_topU3l_MwScheme_UFO_ctGpatched/
  ├── TT01j2lBSMRef/
  ├── TT01j2lBSMRef_ctGIm_m4/
  ├── TT01j2lBSMRef_ctGIm_m2/
  ├── TT01j2lBSMRef_ctGIm_p0/
  └── ...

It also writes:

  run_all_80_no_reweight_gridpacks.sh

The generated runner contains one standalone command per gridpack job, e.g.

  ./gridpack_generation.sh <name> addons/cards/SMEFTsim_topU3l_MwScheme_UFO_ctGpatched/<name> local ALL slc7_amd64_gcc700 CMSSW_10_6_19

The generated runner intentionally contains no environment setup; each SLURM job should cd to the absolute MadGraph directory and set PRODHOME/SCRAM_ARCH/CMSSW_VERSION itself.

It intentionally does NOT create/copy <name>_reweight_card.dat.\nIt also removes run-card options incompatible with MG5 2.6.5, such as sde_strategy.
"""

